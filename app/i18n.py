class Translator:
    def __init__(self, lang="fr"):
        self.lang = lang if lang in LANGUES else "fr"

    def set(self, lang):
        if lang in LANGUES:
            self.lang = lang

    def __call__(self, cle, **kw):
        texte = STRINGS.get(self.lang, STRINGS["fr"]).get(cle, cle)
        return texte.format(**kw) if kw else texte
